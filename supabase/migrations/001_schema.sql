-- ============================================================================
-- SVR Production Log — 001: schema
-- Safe to run on an existing database: every statement is idempotent and
-- nothing is dropped. Review the date-uniqueness note at the bottom first.
-- ============================================================================

-- ---------- profiles -------------------------------------------------------
create table if not exists public.profiles (
  id         uuid primary key references auth.users (id) on delete cascade,
  full_name  text not null default '',
  role       text not null default 'viewer',
  created_at timestamptz not null default now()
);
alter table public.profiles add column if not exists email text;
alter table public.profiles add column if not exists created_at timestamptz not null default now();

do $$
begin
  if not exists (
    select 1 from pg_constraint
    where conrelid = 'public.profiles'::regclass and conname = 'profiles_role_check'
  ) then
    alter table public.profiles
      add constraint profiles_role_check check (role in ('admin', 'supervisor', 'viewer'));
  end if;
end $$;

-- ---------- machines -------------------------------------------------------
create table if not exists public.machines (
  id           bigint generated by default as identity primary key,
  machine_code text not null unique,
  machine_name text not null,
  description  text,
  is_active    boolean not null default true,
  created_at   timestamptz not null default now()
);

-- ---------- parts ----------------------------------------------------------
create table if not exists public.parts (
  id          bigint generated by default as identity primary key,
  part_code   text not null unique,
  part_name   text not null,
  description text,
  is_active   boolean not null default true,
  created_at  timestamptz not null default now()
);

-- ---------- production_logs ------------------------------------------------
create table if not exists public.production_logs (
  id         bigint generated by default as identity primary key,
  log_date   date not null,
  notes      text,
  created_by uuid references auth.users (id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

-- ---------- production_entries --------------------------------------------
create table if not exists public.production_entries (
  id         bigint generated by default as identity primary key,
  log_id     bigint not null references public.production_logs (id) on delete cascade,
  machine_id bigint not null references public.machines (id) on delete restrict,
  part_id    bigint not null references public.parts (id) on delete restrict,
  quantity   integer not null check (quantity >= 0),
  notes      text
);
alter table public.production_entries add column if not exists notes text;

-- ---------- indexes --------------------------------------------------------
create index if not exists production_logs_date_idx
  on public.production_logs (log_date desc, id desc);
create index if not exists production_entries_log_idx
  on public.production_entries (log_id);
create index if not exists production_entries_machine_idx
  on public.production_entries (machine_id);
create index if not exists production_entries_part_idx
  on public.production_entries (part_id);

-- ---------- one log per factory date --------------------------------------
-- Decision: one production log per calendar date. Many machine/part entries
-- live inside that single daily log. This FAILS (by design) if the table
-- already holds two logs for the same date — merge or move them, then re-run.
create unique index if not exists production_logs_log_date_key
  on public.production_logs (log_date);

-- ---------- updated_at maintenance ----------------------------------------
create or replace function public.set_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists production_logs_set_updated_at on public.production_logs;
create trigger production_logs_set_updated_at
  before update on public.production_logs
  for each row execute function public.set_updated_at();
